// Pins the CDN assets that exported pages and sites load (improvement roadmap t-14, CL-08). Each asset is the exact
// version the extension bundles (the one package-lock.json installs into node_modules), and its integrity hash is
// computed from the bytes of that file. jsDelivr serves an npm package's files unchanged at /npm/<name>@<version>/,
// so these are the bytes behind each URL; `node scripts/cdn-pins.mjs --verify` fetches every URL and compares.
//
// `npm run build` writes src/core/cdnPins.ts from here. Run on its own, the script writes it too.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The assets: the key the renderers use, the npm package, and the file inside it. */
export const CDN_SOURCES = [
  { key: 'katexCss', package: 'katex', file: 'dist/katex.min.css' },
  { key: 'mermaidJs', package: 'mermaid', file: 'dist/mermaid.min.js' },
];

/** `sha384-<base64>` of some bytes, the form an `integrity` attribute takes. */
export const integrityOf = (bytes) => `sha384-${createHash('sha384').update(bytes).digest('base64')}`;

/** Every pin, from the packages installed under `root`/node_modules. */
export function cdnPins(root = ROOT) {
  return CDN_SOURCES.map((source) => {
    const dir = join(root, 'node_modules', source.package);
    const { version } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    return {
      key: source.key,
      package: source.package,
      version,
      file: source.file,
      url: `https://cdn.jsdelivr.net/npm/${source.package}@${version}/${source.file}`,
      integrity: integrityOf(readFileSync(join(dir, source.file))),
    };
  });
}

/** The text of src/core/cdnPins.ts for these pins. */
export function cdnPinsModule(pins) {
  const entries = pins.map(({ key, ...pin }) => `  ${key}: {\n${Object.entries(pin).map(([name, value]) => `    ${name}: '${value}',`).join('\n')}\n  },`);
  return [
    '// Generated by scripts/cdn-pins.mjs from the package versions the extension bundles. Do not edit: `npm run build`',
    '// rewrites it, and test/cdnAssets.test.ts fails when it no longer matches node_modules.',
    '',
    '/** The CDN assets exported pages and sites load, each pinned to an exact version with the hash of its bytes. */',
    'export const CDN_PINS = {',
    ...entries,
    '} as const;',
    '',
  ].join('\n');
}

/** Write src/core/cdnPins.ts when it differs, and say whether it changed. */
export function writeCdnPins(root = ROOT) {
  const file = join(root, 'src', 'core', 'cdnPins.ts');
  const text = cdnPinsModule(cdnPins(root));
  let old = '';
  try { old = readFileSync(file, 'utf8'); } catch { /* first run */ }
  if (old.replace(/\r\n/g, '\n') === text) return false;
  writeFileSync(file, text);
  return true;
}

/** Fetch every pinned URL and compare its bytes with the pin; the list of mismatches (empty when all match). */
export async function verifyCdnPins(root = ROOT) {
  const problems = [];
  for (const pin of cdnPins(root)) {
    const response = await fetch(pin.url, { signal: AbortSignal.timeout(30_000) });
    if (!response.ok) problems.push(`${pin.url}: HTTP ${response.status}`);
    else {
      const served = integrityOf(Buffer.from(await response.arrayBuffer()));
      if (served !== pin.integrity) problems.push(`${pin.url}: served ${served}, pinned ${pin.integrity}`);
    }
  }
  return problems;
}

/** `--verify`: compare with the CDN; otherwise write the module. No top-level await: tests load this file as CommonJS. */
function main() {
  if (!process.argv.includes('--verify')) {
    console.log(writeCdnPins() ? 'Wrote src/core/cdnPins.ts.' : 'src/core/cdnPins.ts is up to date.');
    return;
  }
  verifyCdnPins().then((problems) => {
    for (const problem of problems) console.error(problem);
    if (problems.length) process.exitCode = 1;
    else console.log('Every pinned CDN asset matches its integrity hash.');
  }, (err) => {
    console.error(err instanceof Error ? err.message : String(err));
    process.exitCode = 1;
  });
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
